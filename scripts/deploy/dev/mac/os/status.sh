# ----------------------------------------------------------------------------------------------------------------------
# Tools - VM ( Instance )
# ----------------------------------------------------------------------------------------------------------------------

setTools() {
  echo "---------------------------------------------------------------------------------------------------------------"
  echo "[ ${ENVIRONMENT_NAME} ] ${PLATFORM_TYPE} - Tools - VM ( Instance )"
  echo "---------------------------------------------------------------------------------------------------------------"
  echo

  if [ "${PLATFORM_TYPE}" == "Darwin" ]; then
    # >>>> Environment
    if [ "${ENVIRONMENT_NAME}" == "dev" ]; then

      # >>>> Host
      scutil --get HostName
      echo

      uname -n
      echo

      arp -a
      echo

      # >>>> Hardware
      networksetup -listallhardwareports
      echo

      netstat -rn
      echo

      ifconfig
      echo

      scutil --dns
      echo

      # >>>> Firewall - Application Firewall
      sudo /usr/libexec/ApplicationFirewall/socketfilterfw --getglobalstate
      echo

      sudo /usr/libexec/ApplicationFirewall/socketfilterfw --listapps
      echo

      # >>>> status
      netstat -an -f inet
      echo

      netstat -i
      echo

      netstat -s
      echo

      sudo lsof -nP -iTCP -sTCP:LISTEN
      echo

      # ------------------------------------------------------------------------------------------------------------------
      # Security - Logs
      # ------------------------------------------------------------------------------------------------------------------
      # BSD date: -v-1H means "one hour ago" (GNU date -d is unavailable on macOS)
      ONE_HOUR_AGO=$(date -v-1H '+%Y-%m-%d %H:%M:%S')

      # NSPredicate: an unquoted bareword (error) is parsed as a keypath, not a string.
      # messageType is numeric — 16 == Error — so compare against the numeric level.
      log show --predicate 'messageType == 16' --start "${ONE_HOUR_AGO}" --no-pager
      echo

    fi

  fi
  echo

  echo ">>>> Tools - IDE : AI"
  echo

}

