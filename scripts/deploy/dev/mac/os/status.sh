# ----------------------------------------------------------------------------------------------------------------------
# Docker - Containers
# ----------------------------------------------------------------------------------------------------------------------

setDocker() {
  echo "---------------------------------------------------------------------------------------------------------------"
  echo "[ ${ENVIRONMENT_NAME} ] ${PLATFORM_TYPE} - Docker - Containers"
  echo "---------------------------------------------------------------------------------------------------------------"
  echo

  # >>>> Environment
  if [ "${ENVIRONMENT_NAME}" == "dev" ]; then

    # >>>> Docker Desktop                                                               https://docs.docker.com/reference/
    echo ">>>> Docker Version"
    echo
    docker version
    echo

    echo ">>>> Docker Info"
    echo
    docker info
    echo

    # >>>> Docker - System
    echo ">>>> Docker - System"
    echo

    docker system df
    echo

    # >>>> Docker - Images
    echo ">>>> Docker - images"
    echo

    docker image ls
    echo

    # >>>> Docker - Container
    echo ">>>> Docker - Container"
    echo

    docker container ls
    echo

  fi
}

